"""
Stratified sample of 100 tickets for human annotation study (IAA).

Samples proportionally from each L1 class in the combined train+val+test corpus,
exports two identical spreadsheets (one per annotator) with blank rating columns.

Usage:
    python scripts/sample_for_annotation.py \
        --train data/processed/train.csv \
        --val   data/processed/val.csv \
        --test  data/processed/test.csv \
        --n 100 \
        --seed 42 \
        --output annotation/

Output:
    annotation/annotation_rater_A.csv
    annotation/annotation_rater_B.csv
    annotation/annotation_rubric.txt
"""

import argparse
import os
from pathlib import Path
import pandas as pd
import numpy as np

RUBRIC = """
Human Validation Study — Annotation Rubric
===========================================

You will review ~100 Egyptian Arabic IT support tickets generated by a large
language model (Google Gemini). For each ticket, fill in FOUR columns.

─────────────────────────────────────────────────────────────────
COLUMN 1: naturalness (1-5)
─────────────────────────────────────────────────────────────────
How natural does this ticket sound as a real message written by an
Egyptian employee to an IT helpdesk?

  5 = Completely natural -- could pass as a real ticket with no issues
  4 = Mostly natural -- minor awkwardness or slightly formulaic wording
  3 = Partially natural -- some unnatural phrasing or templated structure
  2 = Mostly unnatural -- clearly machine-generated in style or structure
  1 = Completely unnatural -- would not be mistaken for a real ticket

─────────────────────────────────────────────────────────────────
COLUMNS 2-4: l1_correct / l2_correct / l3_correct  (Y / N / U)
─────────────────────────────────────────────────────────────────
Does each assigned label correctly describe the ticket content?
Use the taxonomy reference below to judge L2 and L3.

  Y = Yes, this label is correct for this ticket
  N = No, this label is wrong -- the ticket clearly belongs elsewhere
  U = Uncertain -- plausible but ambiguous

Rate each level independently. A ticket can have a correct L1 but
a wrong L2 (misassigned subcategory), so check each one separately.

─────────────────────────────────────────────────────────────────
TAXONOMY REFERENCE (L1 > L2 > L3)
─────────────────────────────────────────────────────────────────

ACCESS
  Account
    - Account Locked       (account blocked after failed login attempts)
    - Password Reset       (request to reset a forgotten/expired password)
    - Profile Update       (update name, email, or other profile fields)
  MFA/SSO
    - Authenticator Issue  (authenticator app not working)
    - MFA Failure          (multi-factor authentication failing at login)
    - SSO Login Issue      (single sign-on not working for a service)
  Permissions
    - Admin Access         (request for administrator-level privileges)
    - Permission Denied    (blocked from accessing a resource or system)
    - Role Request         (request to be added to a group or role)

HARDWARE
  Laptop/Desktop
    - Battery              (battery not charging or draining fast)
    - Boot Issue           (computer not starting or stuck at boot)
    - Performance          (device slow, freezing, or overheating)
  Peripherals
    - Docking Station      (dock not connecting or charging)
    - Keyboard/Mouse       (input devices not working)
    - Monitor              (screen display issues)
  Printer/Scanner
    - Driver               (printer driver missing or corrupt)
    - Paper Jam            (paper stuck in printer)
    - Print Failure        (printing fails or produces wrong output)

NETWORK
  Internet/LAN
    - DNS                  (domain name resolution errors)
    - Latency              (slow or high-ping connection)
    - No Internet          (no network connectivity)
  VPN
    - Connection Failure   (VPN client fails to connect)
    - Credentials          (VPN username/password issues)
    - Split Tunnel         (routing or split-tunnel configuration)
  WiFi
    - Authentication       (WiFi password or certificate error)
    - Connectivity         (connected but no traffic / drops)
    - Slow Speed           (WiFi connection is slow)

SECURITY
  Malware/Phishing
    - Phishing Email       (suspicious email received)
    - Suspicious Link      (user clicked or received a suspicious link)
    - Virus Alert          (antivirus alert or suspected infection)
  Policy/Compliance
    - Blocked Site         (website blocked by company policy)
    - Data Access          (data privacy or access policy concern)
    - Device Encryption    (encryption status or BitLocker issue)

SERVICE
  Incident
    - Degradation          (service partially working but degraded)
    - Intermittent         (service works sometimes, fails sometimes)
    - Outage               (service completely down)
  Request
    - New Account          (request to create a new user account)
    - New Device           (request for a new laptop, phone, etc.)
    - Software Install     (request to install an application)

SOFTWARE
  Business App
    - Bug                  (bug or error in a business application)
    - Feature Request      (request for a new feature in an app)
    - Integration          (app integration or API connection issue)
  Email/Calendar
    - Mailbox Access       (cannot open or access mailbox)
    - Outlook Issue        (Outlook client not working)
    - Sync Problem         (email/calendar not syncing)
  Office Apps
    - Crash                (Office application crashing)
    - License              (Office license expired or not activated)
    - Word/Excel           (specific Word or Excel problem)

─────────────────────────────────────────────────────────────────
GENERAL INSTRUCTIONS
─────────────────────────────────────────────────────────────────
- Read title_ar and description_ar together before rating
- Fill all four columns for every row -- do not leave blanks
- Do not discuss your ratings with the other annotator until both
  files are returned
- If a ticket's Arabic is incomprehensible, rate naturalness=1
  and all label columns=U
- Estimated time: 45-60 minutes for ~100 tickets
"""


def main():
    repo_root = Path(__file__).resolve().parents[1]
    classification_root = repo_root.parent / "arabic-itsm-classification"
    parser = argparse.ArgumentParser()
    parser.add_argument("--train", default=str(classification_root / "data/processed/train.csv"))
    parser.add_argument("--val", default=str(classification_root / "data/processed/val.csv"))
    parser.add_argument("--test", default=str(classification_root / "data/processed/test.csv"))
    parser.add_argument("--n", type=int, default=100)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", default=str(repo_root / "annotation_working"))
    args = parser.parse_args()

    dfs = []
    for path in [args.train, args.val, args.test]:
        df = pd.read_csv(path)
        dfs.append(df)
    corpus = pd.concat(dfs, ignore_index=True)

    # Stratified sample proportional to L1 distribution
    rng = np.random.default_rng(args.seed)
    l1_counts = corpus["category_level_1"].value_counts(normalize=True)
    samples = []
    for l1, prop in l1_counts.items():
        n_class = max(1, round(prop * args.n))
        pool = corpus[corpus["category_level_1"] == l1]
        n_class = min(n_class, len(pool))
        idx = rng.choice(len(pool), size=n_class, replace=False)
        samples.append(pool.iloc[idx])

    sample_df = pd.concat(samples, ignore_index=True).sample(
        frac=1, random_state=args.seed
    ).reset_index(drop=True)

    # Keep only human-readable columns + add blank rating columns
    out = sample_df[[
        "ticket_id", "title_ar", "description_ar",
        "category_level_1", "category_level_2", "category_level_3",
        "priority", "sentiment",
    ]].copy()
    out.rename(columns={
        "category_level_1": "L1_label",
        "category_level_2": "L2_label",
        "category_level_3": "L3_label",
    }, inplace=True)
    out["naturalness (1-5)"] = ""
    out["l1_correct (Y/N/U)"] = ""
    out["l2_correct (Y/N/U)"] = ""
    out["l3_correct (Y/N/U)"] = ""

    os.makedirs(args.output, exist_ok=True)
    for rater in ["A", "B"]:
        path = os.path.join(args.output, f"annotation_rater_{rater}.csv")
        out.to_csv(path, index=False, encoding="utf-8-sig")
        print(f"Saved: {path}")

    rubric_path = os.path.join(args.output, "annotation_rubric.txt")
    with open(rubric_path, "w", encoding="utf-8") as f:
        f.write(RUBRIC)
    print(f"Saved: {rubric_path}")
    print(f"\nSample size: {len(out)} tickets")
    print("L1 distribution in sample:")
    print(out["L1_label"].value_counts().to_string())


if __name__ == "__main__":
    main()
