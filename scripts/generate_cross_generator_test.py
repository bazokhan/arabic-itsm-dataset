"""
Cross-generator test set generation using Claude (Anthropic API).

Addresses reviewer Issue #1: the entire dataset was generated by a single LLM
(Gemini). This script generates ~300 tickets using Claude to create a
cross-generator validation set for external validity assessment.

The same taxonomy (6 L1, 16 L2, 48 L3) and schema are used, but the
generating model is different — testing whether trained models generalize
beyond the Gemini-generated training distribution.

Target: ~6–7 tickets per L3 class (48 classes × 6 = 288 ≈ 300 tickets)

Usage:
    pip install anthropic
    export ANTHROPIC_API_KEY=sk-ant-...
    python scripts/generate_cross_generator_test.py
    python scripts/generate_cross_generator_test.py --n-per-l3 6 --output cross_generator_test

Outputs:
    cross_generator_test.csv
    cross_generator_test.jsonl
"""

import argparse
import json
import os
import random
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

import anthropic
import pandas as pd


TAXONOMY_PATH = Path(__file__).parent.parent / "taxonomy_itsm_v1.json"

GENERATION_SYSTEM = """You are generating synthetic Egyptian Arabic IT helpdesk support tickets.
You write realistic ticket descriptions that IT staff would submit when experiencing technical problems.
Your output must be valid JSON Lines (JSONL) — one JSON object per line, no markdown, no extra text."""

GENERATION_PROMPT_TEMPLATE = """Generate {n} Egyptian Arabic IT support tickets for the following category:
- L1: {l1}
- L2: {l2}
- L3: {l3}

Requirements:
1. Write in Egyptian colloquial Arabic (عامية مصرية) mixed with technical English terms (VPN, Outlook, MFA, WiFi, etc.)
2. Each ticket must have a short title_ar and a longer description_ar (3–6 sentences)
3. Vary the writing style: some formal, some frustrated, some very brief, some detailed
4. Priority must follow the rule: priority = round((impact + urgency) / 2), clamped 1..5
5. Sentiment must match the tone of the text

Output EXACTLY {n} JSON objects, one per line, with this schema:
{{
  "ticket_id": "XGEN-{l1_code}-NNNN",
  "model": "claude",
  "dialect": "Egyptian",
  "title_ar": "<short Arabic title>",
  "description_ar": "<multi-sentence Arabic description>",
  "category_level_1": "{l1}",
  "category_level_2": "{l2}",
  "category_level_3": "{l3}",
  "impact": <1-5>,
  "urgency": <1-5>,
  "priority": <1-5 following the formula>,
  "sentiment": "<positive|neutral|negative|mixed>"
}}

Return ONLY the JSON lines, no commentary."""


def load_taxonomy(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["taxonomy"]


def build_all_combinations(taxonomy: list[dict]) -> list[tuple[str, str, str]]:
    """Return all valid (L1, L2, L3) tuples."""
    combos = []
    for entry in taxonomy:
        l1 = entry["l1"]
        l2 = entry["l2"]
        for l3 in entry["l3"]:
            combos.append((l1, l2, l3))
    return combos


def generate_tickets_for_l3(
    client: anthropic.Anthropic,
    l1: str, l2: str, l3: str,
    n: int,
    model: str = "claude-opus-4-6",
    max_retries: int = 3,
) -> list[dict]:
    """Call Claude API to generate n tickets for one L3 class."""
    l1_code = l1[:3].upper()
    prompt = GENERATION_PROMPT_TEMPLATE.format(
        n=n, l1=l1, l2=l2, l3=l3, l1_code=l1_code
    )

    for attempt in range(1, max_retries + 1):
        try:
            msg = client.messages.create(
                model=model,
                max_tokens=2000,
                system=GENERATION_SYSTEM,
                messages=[{"role": "user", "content": prompt}],
            )
            raw = msg.content[0].text.strip()
            tickets = []
            for line in raw.splitlines():
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                try:
                    obj = json.loads(line)
                    # Validate required fields
                    if all(k in obj for k in ["title_ar", "description_ar", "priority", "sentiment"]):
                        # Enforce category fields
                        obj["category_level_1"] = l1
                        obj["category_level_2"] = l2
                        obj["category_level_3"] = l3
                        obj["model"] = "claude"
                        obj["dialect"] = "Egyptian"
                        tickets.append(obj)
                except json.JSONDecodeError:
                    continue

            if tickets:
                return tickets
            print(f"    Attempt {attempt}: No valid tickets parsed, retrying...")
        except anthropic.APIError as e:
            print(f"    Attempt {attempt}: API error: {e}")
            time.sleep(2 ** attempt)

    return []


def assign_ids_and_timestamps(tickets: list[dict]) -> list[dict]:
    """Add ticket_id, created_at, updated_at if missing."""
    rng = random.Random(42)
    base_date = datetime(2026, 1, 1, tzinfo=timezone.utc)

    for i, t in enumerate(tickets):
        if not t.get("ticket_id") or not str(t.get("ticket_id", "")).startswith("X"):
            t["ticket_id"] = f"XGEN-{i+1:05d}"
        if not t.get("created_at"):
            offset_hours = rng.randint(0, 8760)
            ts = base_date + timedelta(hours=offset_hours)
            t["created_at"] = ts.isoformat()
        if not t.get("updated_at"):
            created = datetime.fromisoformat(t["created_at"])
            t["updated_at"] = (created + timedelta(hours=rng.randint(0, 48))).isoformat()

    return tickets


def validate_priority(tickets: list[dict]) -> list[dict]:
    """Enforce priority formula and clamp to 1..5."""
    for t in tickets:
        if "impact" in t and "urgency" in t:
            correct = max(1, min(5, round((t["impact"] + t["urgency"]) / 2)))
            t["priority"] = correct
    return tickets


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-per-l3", type=int, default=6,
                        help="Tickets per L3 class (default 6 → ~288 total)")
    parser.add_argument("--output", default="cross_generator_test",
                        help="Output filename stem (no extension)")
    parser.add_argument("--model", default="claude-opus-4-6",
                        help="Claude model to use")
    parser.add_argument("--rate-limit-delay", type=float, default=1.0,
                        help="Seconds to wait between API calls")
    args = parser.parse_args()

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        raise EnvironmentError("ANTHROPIC_API_KEY environment variable not set.")

    client = anthropic.Anthropic(api_key=api_key)

    taxonomy = load_taxonomy(TAXONOMY_PATH)
    combinations = build_all_combinations(taxonomy)
    total_expected = len(combinations) * args.n_per_l3
    print(f"Taxonomy: {len(combinations)} L3 classes")
    print(f"Target: {args.n_per_l3} tickets/class × {len(combinations)} = {total_expected} tickets")
    print(f"Model: {args.model}")

    all_tickets: list[dict] = []
    failed: list[tuple] = []

    for idx, (l1, l2, l3) in enumerate(combinations):
        print(f"[{idx+1}/{len(combinations)}] {l1} > {l2} > {l3}", end=" ... ")
        tickets = generate_tickets_for_l3(client, l1, l2, l3, args.n_per_l3, args.model)

        if tickets:
            print(f"✓ {len(tickets)} tickets")
            all_tickets.extend(tickets)
        else:
            print("✗ FAILED")
            failed.append((l1, l2, l3))

        time.sleep(args.rate_limit_delay)

    print(f"\nGenerated: {len(all_tickets)} tickets | Failed: {len(failed)} L3 classes")
    if failed:
        print("Failed classes:")
        for f in failed:
            print(f"  {f[0]} > {f[1]} > {f[2]}")

    # Post-process
    all_tickets = assign_ids_and_timestamps(all_tickets)
    all_tickets = validate_priority(all_tickets)

    # Save
    output_csv = Path(__file__).parent.parent / f"{args.output}.csv"
    output_jsonl = Path(__file__).parent.parent / f"{args.output}.jsonl"

    df = pd.DataFrame(all_tickets)

    # Ensure consistent column order
    cols_order = [
        "ticket_id", "created_at", "updated_at", "model", "dialect",
        "title_ar", "description_ar",
        "category_level_1", "category_level_2", "category_level_3",
        "impact", "urgency", "priority", "sentiment",
    ]
    for col in cols_order:
        if col not in df.columns:
            df[col] = None
    df = df[cols_order + [c for c in df.columns if c not in cols_order]]

    df.to_csv(output_csv, index=False, encoding="utf-8")
    with open(output_jsonl, "w", encoding="utf-8") as f:
        for ticket in all_tickets:
            f.write(json.dumps(ticket, ensure_ascii=False) + "\n")

    print(f"\nSaved: {output_csv} ({len(df)} rows)")
    print(f"Saved: {output_jsonl}")
    print("\nDistribution check:")
    for l1, grp in df.groupby("category_level_1"):
        print(f"  {l1}: {len(grp)} tickets")


if __name__ == "__main__":
    main()
