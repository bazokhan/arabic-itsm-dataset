"""
Cross-generator test set generation using Claude (Anthropic API).

Addresses reviewer Issue #1: the entire dataset was generated by a single LLM
(Gemini). This script generates ~144 tickets using Claude to create a
cross-generator validation set for external validity assessment.

Strategy: batch all L3 classes under each L2 into ONE API call (16 calls
instead of 48). The model sees sibling L3 classes together, producing more
discriminative tickets. Each call generates 3 tickets per L3 child.

Cost estimate: ~$0.50-$0.80 with claude-sonnet-4-6 (16 calls x ~3K tokens out)

Usage:
    export ANTHROPIC_API_KEY=sk-ant-...
    python scripts/generate_cross_generator_test.py

Outputs:
    cross_generator_test.csv
    cross_generator_test.jsonl
"""

import argparse
import json
import os
import random
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

import anthropic
import pandas as pd


TAXONOMY_PATH = Path(__file__).parent.parent / "taxonomy_itsm_v1.json"

GENERATION_SYSTEM = """You are generating synthetic Egyptian Arabic IT helpdesk support tickets.
You write realistic ticket descriptions that IT staff would submit when experiencing technical problems.
Your output must be valid JSON Lines (JSONL) — one JSON object per line, no markdown, no extra text."""

GENERATION_PROMPT_TEMPLATE = """Generate exactly {n_total} Egyptian Arabic IT support tickets.
The tickets cover L1="{l1}", L2="{l2}". Generate {n_per_l3} tickets for EACH of these L3 categories:

{l3_list}

Requirements:
1. Write in Egyptian colloquial Arabic (عامية مصرية) mixed with technical English terms (VPN, Outlook, MFA, WiFi, etc.)
2. Each ticket: short title_ar (5-10 words), longer description_ar (3-6 sentences)
3. Vary the writing style: some formal, some frustrated, some very brief, some detailed
4. Priority = round((impact + urgency) / 2), clamped 1..5
5. Sentiment must match the tone of the text

Output EXACTLY {n_total} JSON objects (one per line), in order of the L3 categories listed above
({n_per_l3} tickets per category, so the first {n_per_l3} lines are for the first L3, etc.).
Each JSON must include:
{{
  "title_ar": "<short Arabic title>",
  "description_ar": "<multi-sentence Arabic description>",
  "category_level_3": "<exact L3 name from the list above>",
  "impact": <1-5>,
  "urgency": <1-5>,
  "priority": <1-5 following the formula>,
  "sentiment": "<positive|neutral|negative|mixed>"
}}

Return ONLY the {n_total} JSON lines, no commentary, no numbering, no separators."""


def load_taxonomy(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["taxonomy"]


def build_l2_groups(taxonomy: list[dict]) -> list[dict]:
    """Return list of {l1, l2, l3_list} groups for each L2 category."""
    groups = []
    for entry in taxonomy:
        groups.append({
            "l1": entry["l1"],
            "l2": entry["l2"],
            "l3_list": entry["l3"],
        })
    return groups


def generate_tickets_for_l2(
    client: anthropic.Anthropic,
    l1: str,
    l2: str,
    l3_list: list[str],
    n_per_l3: int,
    model: str = "claude-sonnet-4-6",
    max_retries: int = 3,
) -> list[dict]:
    """Call Claude API once to generate n_per_l3 tickets for every L3 under this L2."""
    n_total = len(l3_list) * n_per_l3
    l3_formatted = "\n".join(f"  {i+1}. {l3}" for i, l3 in enumerate(l3_list))

    prompt = GENERATION_PROMPT_TEMPLATE.format(
        n_total=n_total,
        n_per_l3=n_per_l3,
        l1=l1,
        l2=l2,
        l3_list=l3_formatted,
    )

    # Generous token budget: ~600 tokens per ticket
    max_tokens = n_total * 700 + 200

    for attempt in range(1, max_retries + 1):
        try:
            msg = client.messages.create(
                model=model,
                max_tokens=max_tokens,
                system=GENERATION_SYSTEM,
                messages=[{"role": "user", "content": prompt}],
            )
            raw = msg.content[0].text.strip()
            tickets = []
            for line in raw.splitlines():
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                try:
                    obj = json.loads(line)
                    if all(k in obj for k in ["title_ar", "description_ar", "priority", "sentiment"]):
                        # Validate category_level_3 is one of expected L3 classes
                        l3_val = obj.get("category_level_3", "")
                        if l3_val not in l3_list:
                            # Try to infer from position if model forgot the field
                            pos = len(tickets)
                            l3_val = l3_list[min(pos // n_per_l3, len(l3_list) - 1)]
                        obj["category_level_1"] = l1
                        obj["category_level_2"] = l2
                        obj["category_level_3"] = l3_val
                        obj["model"] = "claude"
                        obj["dialect"] = "Egyptian"
                        tickets.append(obj)
                except json.JSONDecodeError:
                    continue

            if len(tickets) >= n_total // 2:  # Accept if at least half parsed
                return tickets
            print(f"    Attempt {attempt}: only {len(tickets)}/{n_total} parsed, retrying...")
        except anthropic.APIError as e:
            print(f"    Attempt {attempt}: API error: {e}")
            time.sleep(2 ** attempt)

    return []


def assign_ids_and_timestamps(tickets: list[dict]) -> list[dict]:
    rng = random.Random(42)
    base_date = datetime(2026, 1, 1, tzinfo=timezone.utc)
    for i, t in enumerate(tickets):
        t["ticket_id"] = f"XGEN-{i+1:05d}"
        offset_hours = rng.randint(0, 8760)
        ts = base_date + timedelta(hours=offset_hours)
        t["created_at"] = ts.isoformat()
        t["updated_at"] = (ts + timedelta(hours=rng.randint(0, 48))).isoformat()
    return tickets


def validate_priority(tickets: list[dict]) -> list[dict]:
    for t in tickets:
        if "impact" in t and "urgency" in t:
            t["priority"] = max(1, min(5, round((t["impact"] + t["urgency"]) / 2)))
    return tickets


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-per-l3", type=int, default=3,
                        help="Tickets per L3 class (default 3 -> 144 total via 16 batched calls)")
    parser.add_argument("--output", default="cross_generator_test",
                        help="Output filename stem (no extension)")
    parser.add_argument("--model", default="claude-sonnet-4-6",
                        help="Claude model to use")
    parser.add_argument("--rate-limit-delay", type=float, default=0.5,
                        help="Seconds to wait between API calls")
    args = parser.parse_args()

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        raise EnvironmentError("ANTHROPIC_API_KEY environment variable not set.")

    client = anthropic.Anthropic(api_key=api_key)

    taxonomy = load_taxonomy(TAXONOMY_PATH)
    groups = build_l2_groups(taxonomy)
    total_l3 = sum(len(g["l3_list"]) for g in groups)
    total_expected = total_l3 * args.n_per_l3

    print(f"Strategy: {len(groups)} batched API calls (one per L2 category)")
    print(f"Target: {args.n_per_l3} tickets x {total_l3} L3 classes = {total_expected} tickets")
    print(f"Model: {args.model}")
    print()

    all_tickets: list[dict] = []
    failed: list[str] = []

    for idx, group in enumerate(groups):
        l1, l2, l3_list = group["l1"], group["l2"], group["l3_list"]
        n_expected = len(l3_list) * args.n_per_l3
        print(f"[{idx+1}/{len(groups)}] {l1} > {l2} ({len(l3_list)} L3 classes, {n_expected} tickets)...", end=" ", flush=True)

        tickets = generate_tickets_for_l2(client, l1, l2, l3_list, args.n_per_l3, args.model)

        if tickets:
            print(f"OK {len(tickets)} tickets")
            all_tickets.extend(tickets)
        else:
            print("FAILED")
            failed.append(f"{l1} > {l2}")

        time.sleep(args.rate_limit_delay)

    print(f"\nGenerated: {len(all_tickets)} tickets | Failed L2 groups: {len(failed)}")
    if failed:
        for f in failed:
            print(f"  {f}")

    all_tickets = assign_ids_and_timestamps(all_tickets)
    all_tickets = validate_priority(all_tickets)

    output_csv = Path(__file__).parent.parent / f"{args.output}.csv"
    output_jsonl = Path(__file__).parent.parent / f"{args.output}.jsonl"

    df = pd.DataFrame(all_tickets)
    cols_order = [
        "ticket_id", "created_at", "updated_at", "model", "dialect",
        "title_ar", "description_ar",
        "category_level_1", "category_level_2", "category_level_3",
        "impact", "urgency", "priority", "sentiment",
    ]
    for col in cols_order:
        if col not in df.columns:
            df[col] = None
    df = df[cols_order + [c for c in df.columns if c not in cols_order]]

    df.to_csv(output_csv, index=False, encoding="utf-8")
    with open(output_jsonl, "w", encoding="utf-8") as f:
        for ticket in all_tickets:
            f.write(json.dumps(ticket, ensure_ascii=False) + "\n")

    print(f"\nSaved: {output_csv} ({len(df)} rows)")
    print(f"Saved: {output_jsonl}")
    print("\nL3 distribution check:")
    l3_counts = df.groupby("category_level_3").size()
    under = l3_counts[l3_counts < args.n_per_l3]
    if len(under) > 0:
        print(f"  WARNING: {len(under)} L3 classes have fewer than {args.n_per_l3} tickets:")
        for l3, cnt in under.items():
            print(f"    {l3}: {cnt}")
    else:
        print(f"  All {total_l3} L3 classes have >= {args.n_per_l3} tickets.")


if __name__ == "__main__":
    main()
